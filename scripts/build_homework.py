"""Generate journal homework from the student lessons; no answer keys are read."""
import argparse
import json
import re
from html.parser import HTMLParser
from pathlib import Path


class Node:
    def __init__(self, tag='', attrs=()):
        self.tag = tag
        self.attrs = dict(attrs)
        self.children = []

    def has_class(self, name):
        return name in self.attrs.get('class', '').split()

    def text(self):
        children = [c for c in self.children if isinstance(c, Node)]
        if self.has_class('fr'):
            if len(children) != 2:
                raise ValueError('Fraction must have numerator and denominator')
            # Keep the whole fraction grouped: a trailing power must not move
            # to the denominator or change precedence in adjacent products.
            return '((' + children[0].text().strip() + ')/(' + children[1].text().strip() + '))'
        content = ''.join(c.text() if isinstance(c, Node) else c for c in self.children)
        if self.has_class('rad'):
            return '(' + content + ')'
        if self.tag == 'sup':
            return '^(' + content + ')'
        if self.has_class('task-no'):
            return content.strip().rstrip('.') + '. '
        if self.tag in ('p', 'br', 'li', 'div'):
            return content + ' '
        return content

    def walk(self):
        yield self
        for child in self.children:
            if isinstance(child, Node):
                yield from child.walk()


class Parser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node()
        self.stack = [self.root]

    def handle_starttag(self, tag, attrs):
        node = Node(tag, attrs)
        self.stack[-1].children.append(node)
        if tag not in ('area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr'):
            self.stack.append(node)

    def handle_endtag(self, tag):
        for i in range(len(self.stack) - 1, 0, -1):
            if self.stack[i].tag == tag:
                del self.stack[i:]
                return

    def handle_data(self, data):
        self.stack[-1].children.append(data)


def clean(text):
    return re.sub(r'\s+', ' ', text).strip()


def extract(html):
    parser = Parser()
    parser.feed(html)
    active = False
    instructions, tasks = [], []
    for node in parser.root.walk():
        if node.attrs.get('id') == 'homework':
            active = True
            continue
        if active and (node.tag == 'h2' or node.has_class('pager') or node.tag == 'footer'):
            break
        if not active:
            continue
        if node.has_class('goal'):
            instructions.append(clean(node.text()))
        if node.has_class('task'):
            tasks.append(clean(node.text()))
    if not tasks or not all(re.match(r'^Д\d+\. ', t) for t in tasks):
        raise ValueError('Homework section with numbered task conditions is required')
    numbers = [int(re.match(r'^Д(\d+)', t)[1]) for t in tasks]
    if numbers != list(range(1, len(tasks) + 1)):
        raise ValueError('Homework task numbering must be consecutive')
    return '\n\n'.join(instructions + tasks)


def build(root):
    return {f'el{i}': extract((root / f'el{i}.html').read_text()) for i in range(1, 21)}


if __name__ == '__main__':
    args = argparse.ArgumentParser()
    args.add_argument('--check', action='store_true')
    options = args.parse_args()
    root = Path(__file__).resolve().parents[1]
    target = root / 'assets/homework-ege.js'
    output = '// Generated by scripts/build_homework.py. Edit homework in el1..el20.html.\nwindow.EDU_EGE_HOMEWORK = ' + json.dumps(build(root), ensure_ascii=False, indent=2) + ';\n'
    if options.check:
        if not target.exists() or target.read_text() != output:
            raise SystemExit('Homework is out of date: run python scripts/build_homework.py')
        print('PASS: generated homework matches all 20 lessons')
    else:
        target.write_text(output)
        print('Generated homework for 20 EGE lessons')
